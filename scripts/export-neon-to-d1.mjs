// Exports all data from the existing Neon Postgres database into a D1-compatible
// SQL file (prisma/d1-data.sql).
//
// Conversions match how Prisma's SQLite connector stores values so the data
// reads back correctly through the Prisma D1 adapter:
//   - DateTime  -> INTEGER (Unix epoch milliseconds)
//   - Boolean   -> INTEGER (0 / 1)
//   - null      -> NULL
//   - strings   -> single-quoted, with '' escaping
//
// Usage:  node scripts/export-neon-to-d1.mjs
// Requires DATABASE_URL (Postgres) — read automatically from .env if present.

import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'
import pg from 'pg'

const __dirname = dirname(fileURLToPath(import.meta.url))
const root = join(__dirname, '..')

function loadEnv() {
  if (process.env.DATABASE_URL) return process.env.DATABASE_URL
  try {
    const raw = readFileSync(join(root, '.env'), 'utf8')
    for (const line of raw.split(/\r?\n/)) {
      const m = line.match(/^\s*DATABASE_URL\s*=\s*(.+)\s*$/)
      if (m) {
        let v = m[1].trim()
        if (
          (v.startsWith('"') && v.endsWith('"')) ||
          (v.startsWith("'") && v.endsWith("'"))
        ) {
          v = v.slice(1, -1)
        }
        return v
      }
    }
  } catch {
    /* ignore */
  }
  return undefined
}

// Tables in FK-safe insert order, with the exact column list from the D1 schema.
const TABLES = [
  {
    name: 'users',
    columns: ['id', 'email', 'name', 'password', 'image', 'role', 'createdAt', 'updatedAt'],
  },
  {
    name: 'accounts',
    columns: [
      'id', 'userId', 'type', 'provider', 'providerAccountId', 'refresh_token',
      'access_token', 'expires_at', 'token_type', 'scope', 'id_token', 'session_state',
    ],
  },
  {
    name: 'materials',
    columns: ['id', 'name', 'description', 'color', 'pricePerGram', 'available', 'printerType', 'createdAt', 'updatedAt'],
  },
  {
    name: 'print_jobs',
    columns: [
      'id', 'userId', 'materialId', 'fileName', 'fileSize', 'printTime', 'materialUsed',
      'baseCost', 'profit', 'totalPrice', 'status', 'notes', 'createdAt', 'updatedAt',
    ],
  },
  {
    name: 'orders',
    columns: ['id', 'userId', 'printJobId', 'status', 'totalAmount', 'notes', 'fileUrl', 'phoneNumber', 'createdAt', 'updatedAt'],
  },
  {
    name: 'order_tracking',
    columns: ['id', 'orderId', 'status', 'description', 'timestamp'],
  },
  {
    name: 'pricing_settings',
    columns: ['id', 'taxRate', 'serviceFee', 'scaleMultiplier', 'updatedAt'],
  },
  {
    name: 'products',
    columns: ['id', 'name', 'description', 'price', 'imageUrl', 'webpUrl', 'category', 'inStock', 'stockCount', 'createdAt', 'updatedAt'],
  },
  {
    name: 'high_scores',
    columns: ['id', 'score', 'playerName', 'updatedAt'],
  },
]

function toSqlValue(value) {
  if (value === null || value === undefined) return 'NULL'
  if (typeof value === 'boolean') return value ? '1' : '0'
  if (value instanceof Date) return String(value.getTime())
  if (typeof value === 'number') return Number.isFinite(value) ? String(value) : 'NULL'
  if (typeof value === 'bigint') return value.toString()
  // Fallback: stringify objects (jsonb etc.) then escape.
  const str = typeof value === 'object' ? JSON.stringify(value) : String(value)
  return `'${str.replace(/'/g, "''")}'`
}

async function main() {
  const connectionString = loadEnv()
  if (!connectionString) {
    console.error('DATABASE_URL not found (env or .env). Aborting.')
    process.exit(1)
  }

  const client = new pg.Client({
    connectionString,
    ssl: { rejectUnauthorized: false },
  })

  await client.connect()
  console.log('Connected to Postgres. Exporting...')

  const out = [
    '-- Auto-generated by scripts/export-neon-to-d1.mjs',
    '-- Data export from Neon Postgres -> Cloudflare D1 (SQLite).',
    'PRAGMA defer_foreign_keys = true;',
    '',
  ]

  let totalRows = 0
  for (const table of TABLES) {
    let rows = []
    try {
      const res = await client.query(`SELECT * FROM "${table.name}"`)
      rows = res.rows
    } catch (err) {
      console.warn(`  ! Skipping "${table.name}": ${err.message}`)
      continue
    }

    out.push(`-- ${table.name} (${rows.length} rows)`)
    const colList = table.columns.map((c) => `"${c}"`).join(', ')
    for (const row of rows) {
      const values = table.columns.map((c) => toSqlValue(row[c])).join(', ')
      out.push(`INSERT OR REPLACE INTO "${table.name}" (${colList}) VALUES (${values});`)
    }
    out.push('')
    totalRows += rows.length
    console.log(`  ${table.name}: ${rows.length} rows`)
  }

  await client.end()

  const target = join(root, 'prisma', 'd1-data.sql')
  writeFileSync(target, out.join('\n'), 'utf8')
  console.log(`\nWrote ${totalRows} rows to ${target}`)
}

main().catch((e) => {
  console.error(e)
  process.exit(1)
})
